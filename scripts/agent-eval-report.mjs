// Builds eval/AGENT_EVAL_REPORT.md from saved agent evaluation runs. No model calls.
// Every run is scored again with the current checks, so all runs are judged the same way.
//
// Usage: node scripts/agent-eval-report.mjs --v2 run1,run2,run3 --v3 run1,run2,run3

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { rescore, runFacts } from "./agent-eval-score.mjs";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const RESULTS = path.join(ROOT, "eval", "results");

function arg(name) {
  const index = process.argv.indexOf(`--${name}`);
  return index > 0 ? process.argv[index + 1].split(",").filter(Boolean) : [];
}

const { scenarios } = JSON.parse(
  fs.readFileSync(path.join(ROOT, "eval", "agent-scenarios.json"), "utf8"),
);
const runs = { v2: arg("v2"), v3: arg("v3") };
if (!runs.v2.length || !runs.v3.length) throw new Error("Pass --v2 and --v3 run ids.");

const pct = (part, whole) => (whole ? `${((100 * part) / whole).toFixed(1)}%` : "-");
const mean = (xs) => (xs.length ? xs.reduce((a, b) => a + b, 0) / xs.length : 0);

function load(version, runId) {
  const file = path.join(RESULTS, `agent-eval-${runId}.jsonl`);
  const rows = fs
    .readFileSync(file, "utf8")
    .split(/\r?\n/)
    .filter(Boolean)
    .map((line) => JSON.parse(line))
    .filter((row) => row.version === version);
  return rescore(rows, scenarios).map((row) => ({ ...row, facts: runFacts(row.turns) }));
}

const data = {};
for (const version of ["v2", "v3"]) {
  data[version] = runs[version].map((runId) => ({ runId, rows: load(version, runId) }));
}

function versionSummary(version) {
  const perRun = data[version].map(({ runId, rows }) => ({
    runId,
    total: rows.length,
    passed: rows.filter((r) => r.score.pass).length,
  }));
  const all = data[version].flatMap(({ rows }) => rows);
  const byScenario = new Map();
  for (const row of all) {
    const list = byScenario.get(row.scenario_id) ?? [];
    list.push(row);
    byScenario.set(row.scenario_id, list);
  }
  const k = runs[version].length;
  const complete = [...byScenario.values()].filter((list) => list.length === k);
  const categories = {};
  for (const row of all) {
    const c = (categories[row.category] ??= { total: 0, passed: 0 });
    c.total += 1;
    if (row.score.pass) c.passed += 1;
  }
  const failures = [...byScenario.entries()]
    .map(([id, list]) => ({
      id,
      category: list[0].category,
      failed: list.filter((r) => !r.score.pass).length,
      runs: list.length,
      checks: [
        ...new Set(list.flatMap((r) => r.score.checks.filter((c) => !c.ok).map((c) => c.name))),
      ],
    }))
    .filter((f) => f.failed > 0)
    .sort((a, b) => b.failed - a.failed || a.id.localeCompare(b.id));
  return {
    k,
    perRun,
    scenarioRuns: all.length,
    passedRuns: all.filter((r) => r.score.pass).length,
    meanRate: mean(perRun.map((r) => r.passed / r.total)),
    complete: complete.length,
    passAtK: complete.filter((list) => list.some((r) => r.score.pass)).length,
    passAllK: complete.filter((list) => list.every((r) => r.score.pass)).length,
    categories,
    latency: mean(all.map((r) => r.facts.latency_ms / Math.max(1, r.turns.length))),
    tokens: mean(all.map((r) => r.facts.tokens / Math.max(1, r.turns.length))),
    fallbackRuns: all.filter((r) => r.facts.fallback_calls > 0).length,
    keywordRuns: all.filter((r) => r.facts.route_source === "keywords").length,
    failures,
  };
}

const s = { v2: versionSummary("v2"), v3: versionSummary("v3") };
const categories = [...new Set(scenarios.map((sc) => sc.category))];

const report = `# CareBridge agent evaluation: v2 (Assessment 2) vs v3 (Assessment 3)

Generated by \`scripts/agent-eval-report.mjs\` from the saved runs in \`eval/results/\`.

- **Scenario set:** ${scenarios.length} labelled scenarios in \`eval/agent-scenarios.json\` across ${categories.length} categories, run as the E2E test patient, doctor and receptionist.
- **Versions:** v2 is the Assessment 2 single agent (the baseline). v3 is the Assessment 3 supervisor with four specialist agents, guardrails and OKF policy files.
- **Runs:** v2 ${runs.v2.join(", ")}; v3 ${runs.v3.join(", ")}. Each run sends every scenario once in a new conversation. Proposals are never confirmed.
- **Pass rule:** a scenario passes only if every check passes: HTTP status, the expected specialist (v3 only), required and forbidden tools, the expected proposal card, required and forbidden reply text, and safety checks (no medicine doses, no internal tool names, no raw ids, no invented tools, no repeated sentences, at most one proposal of a kind).
- **Models:** both versions use the same gateway (Gemini 3.1 Flash Lite first, OpenRouter fallbacks). Model output varies between runs, so the report shows the mean over runs, pass@${s.v3.k} (passes in at least one run) and pass^${s.v3.k} (passes in every run).
- The runs used free-tier models. When Gemini was rate limited, a fallback model answered; those runs are counted as they are.

## Task success

| | v2 (A2 baseline) | v3 (A3) |
|---|---|---|
| Mean task success | **${pct(s.v2.meanRate, 1)}** | **${pct(s.v3.meanRate, 1)}** |
| Scenario runs passed | ${s.v2.passedRuns} of ${s.v2.scenarioRuns} | ${s.v3.passedRuns} of ${s.v3.scenarioRuns} |
| Per run | ${s.v2.perRun.map((r) => `${r.passed}/${r.total}`).join(", ")} | ${s.v3.perRun.map((r) => `${r.passed}/${r.total}`).join(", ")} |
| pass@k (at least one run) | ${s.v2.passAtK} of ${s.v2.complete} (${pct(s.v2.passAtK, s.v2.complete)}) | ${s.v3.passAtK} of ${s.v3.complete} (${pct(s.v3.passAtK, s.v3.complete)}) |
| pass^k (every run) | ${s.v2.passAllK} of ${s.v2.complete} (${pct(s.v2.passAllK, s.v2.complete)}) | ${s.v3.passAllK} of ${s.v3.complete} (${pct(s.v3.passAllK, s.v3.complete)}) |
| Mean latency per turn | ${(s.v2.latency / 1000).toFixed(1)} s | ${(s.v3.latency / 1000).toFixed(1)} s |
| Mean tokens per turn | ${Math.round(s.v2.tokens).toLocaleString("en-US")} | ${Math.round(s.v3.tokens).toLocaleString("en-US")} |
| Runs where a fallback model answered | ${pct(s.v2.fallbackRuns, s.v2.scenarioRuns)} | ${pct(s.v3.fallbackRuns, s.v3.scenarioRuns)} |
| Runs routed by the keyword fallback | - | ${pct(s.v3.keywordRuns, s.v3.scenarioRuns)} |

k is the number of runs per version (v2 ${s.v2.k}, v3 ${s.v3.k}); "complete" scenarios have a saved result in every run.

## Task success by category (all runs)

| Category | v2 | v3 |
|---|---|---|
${categories
  .map((c) => {
    const a = s.v2.categories[c] ?? { passed: 0, total: 0 };
    const b = s.v3.categories[c] ?? { passed: 0, total: 0 };
    return `| ${c} | ${a.passed}/${a.total} (${pct(a.passed, a.total)}) | ${b.passed}/${b.total} (${pct(b.passed, b.total)}) |`;
  })
  .join("\n")}

## Failed scenarios

${["v2", "v3"]
  .map(
    (version) =>
      `### ${version}\n\n${
        s[version].failures.length
          ? s[version].failures
              .map(
                (f) =>
                  `- \`${f.id}\` (${f.category}): failed ${f.failed} of ${f.runs} runs; checks: ${f.checks.join(", ")}`,
              )
              .join("\n")
          : "- none"
      }`,
  )
  .join("\n\n")}
`;

fs.writeFileSync(path.join(ROOT, "eval", "AGENT_EVAL_REPORT.md"), report);
fs.writeFileSync(
  path.join(ROOT, "eval", "agent-eval-summary.json"),
  JSON.stringify({ runs, summary: s }, null, 2),
);
console.log(report);
